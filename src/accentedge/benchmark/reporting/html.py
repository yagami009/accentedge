"""HTML report generation."""
from __future__ import annotations
from pathlib import Path
from dataclasses import asdict
import json

HTML_TEMPLATE = """<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>AccentEdge Benchmark Report</title>
<style>
body { font-family: sans-serif; margin: 2rem; }
table { border-collapse: collapse; margin: 1rem 0; }
th, td { border: 1px solid #ccc; padding: 0.4rem 0.8rem; text-align: left; }
th { background: #f0f0f0; }
.pass { color: green; font-weight: bold; }
.fail { color: red; font-weight: bold; }
.section { margin: 2rem 0; }
h2 { border-bottom: 2px solid #333; padding-bottom: 0.3rem; }
</style></head>
<body>
<h1>AccentEdge BPO Benchmark v1 Report</h1>
<p><strong>Benchmark:</strong> {{benchmark_version}}</p>
<p><strong>Run ID:</strong> {{run_id}}</p>
<p><strong>Candidate:</strong> {{candidate_name}} ({{candidate_version}})</p>
<p><strong>Split:</strong> {{split}} | <strong>Condition:</strong> {{condition}}</p>
<p><strong>Timestamp:</strong> {{timestamp}}</p>

<div class="section">
<h2>Summary</h2>
<table>
<tr><th>Metric</th><th>Value</th><th>CI Lower</th><th>CI Upper</th></tr>
{% for m in summary %}
<tr><td>{{m.metric_name}}</td><td>{{"%.4f"|format(m.value) if m.value is not none else "N/A"}}</td>
<td>{{"%.4f"|format(m.ci_lower) if m.ci_lower is not none else "N/A"}}</td>
<td>{{"%.4f"|format(m.ci_upper) if m.ci_upper is not none else "N/A"}}</td></tr>
{% endfor %}
</table>
</div>

<div class="section">
<h2>Robustness Slices</h2>
<table>
<tr><th>Slice</th><th>WER</th><th>CER</th><th>Damage</th></tr>
{% for slice_name, m in slices.items() %}
<tr><td>{{slice_name}}</td><td>{{m.get('wer', 0):.4f}}</td>
<td>{{m.get('cer', 0):.4f}}</td><td>{{m.get('damage_rate', 0):.4f}}</td></tr>
{% endfor %}
</table>
</div>

<div class="section">
<h2>Failures</h2>
{% if failures %}
<table>
<tr><th>Utterance</th><th>Category</th><th>Error</th></tr>
{% for f in failures %}
<tr><td>{{f.utterance_id}}</td><td>{{f.error_category}}</td><td>{{f.error_message}}</td></tr>
{% endfor %}
</table>
{% else %}
<p class="pass">No failures.</p>
{% endif %}
</div>

<p><em>Generated by AccentEdge BPO Benchmark v1</em></p>
</body></html>
"""


def generate_html_report(
    summary: list[dict[str, Any]],
    slices: dict[str, dict[str, float]],
    failures: list[dict[str, Any]],
    run_manifest: dict[str, Any] | None = None,
    output_path: str | Path = "report.html",
) -> None:
    from jinja2 import Template
    tmpl = Template(HTML_TEMPLATE)
    manifest = run_manifest or {}
    html = tmpl.render(
        benchmark_version=manifest.get("benchmark_version", "1.0.0"),
        run_id=manifest.get("run_id", "unknown"),
        candidate_name=manifest.get("candidate_name", "unknown"),
        candidate_version=manifest.get("candidate_version", "unknown"),
        split=manifest.get("split", "unknown"),
        condition=manifest.get("condition", "unknown"),
        timestamp=manifest.get("timestamp", "unknown"),
        summary=summary,
        slices=slices,
        failures=failures,
    )
    Path(output_path).write_text(html)
